# Provenance labels attached to every financial value the API returns.
OBSERVED = "observed"  # actual reported/market data
EXTERNAL_ESTIMATE = "external_estimate"  # third-party/analyst estimate
MODEL_FORECAST = "model_forecast"  # generated by EventAlpha's quantitative engine


def current_mode(db: Session = Depends(get_db)) -> DataMode:
    return get_data_mode(db)


def api_error(status: int, code: str, message: str) -> HTTPException:
    return HTTPException(status_code=status, detail={"code": code, "message": message})


def require_company(db: Session, ticker: str, mode: str) -> Company:
    try:
        t = normalize_ticker(ticker)
    except AnalysisError as exc:
        raise api_error(400, exc.code, str(exc)) from exc
    c = get_company(db, t, mode)
    if c is None:
        raise api_error(404, "not_analyzed", f"{t} has no data yet in {mode} mode. Run an analysis first.")
    return c


def latest_price(db: Session, company_id: int) -> dict[str, Any] | None:
    """Latest stored (split-adjusted) close with staleness — never fabricated."""
    from app.services.prices import load_adjusted_prices

    df = load_adjusted_prices(db, company_id, start=date.today() - timedelta(days=30))
    if df.empty:
        row = db.scalar(select(StockPrice).where(StockPrice.company_id == company_id).order_by(StockPrice.trade_date.desc()))
        if row is None:
            return None
        df = load_adjusted_prices(db, company_id, start=row.trade_date - timedelta(days=10))
    last = df.iloc[-1]
    d = df.index[-1].date()
    prev = float(df["close"].iloc[-2]) if len(df) > 1 else None
    row = db.scalar(select(StockPrice).where(StockPrice.company_id == company_id, StockPrice.trade_date == d))
    return {
        "price": float(last["close"]), "trade_date": str(d), "change_pct": (float(last["close"]) / prev - 1) if prev else None,
        "volume": float(last["volume"]) if pd.notna(last.get("volume")) else None,
        "kind": "daily_close", "provenance": OBSERVED, "source": row.source if row else None,
        "ingested_at": row.ingested_at.isoformat() if row else None,
        "stale_sessions": trading_days_stale(d),
    }


def scenario_dict(s: ForecastScenario) -> dict[str, Any]:
    return {
        "scenario": s.scenario, "revenue": s.revenue, "revenue_growth": s.revenue_growth,
        "operating_margin": s.operating_margin, "net_margin": s.net_margin, "eps": s.eps,
        "free_cash_flow": s.free_cash_flow, "pe_multiple": s.pe_multiple, "target_price_pe": s.target_price_pe,
        "target_price_dcf": s.target_price_dcf, "target_price_ev_sales": s.target_price_other,
        "target_price": s.target_price, "potential_return": s.potential_return, "explanation": s.explanation,
        "details": s.details, "provenance": MODEL_FORECAST,
    }


def forecast_dict(f: Forecast, include_detail: bool = True) -> dict[str, Any]:
    d: dict[str, Any] = {
        "id": f.id, "analysis_id": f.analysis_id, "created_at": f.created_at.isoformat(),
        "horizon_months": f.horizon_months, "target_date": str(f.target_date),
        "observed_price": f.observed_price, "observed_price_date": str(f.observed_price_date),
        "financial_data_version": f.financial_data_version, "ai_model": f.ai_model,
        "forecast_model_version": f.forecast_model_version, "data_mode": f.data_mode,
        "scenarios": {s.scenario: scenario_dict(s) for s in f.scenarios}, "provenance": MODEL_FORECAST,
    }
    if include_detail:
        d.update({"valuation_methods": f.valuation_methods, "assumptions": f.assumptions, "sensitivity": f.sensitivity,
                  "news_source_ids": f.news_source_ids})
    return d


def analysis_summary(a: Analysis) -> dict[str, Any]:
    s = a.snapshot or {}
    return {
        "id": a.id, "created_at": a.created_at.isoformat(), "data_mode": a.data_mode, "ai_kind": a.ai_kind,
        "ai_model": a.ai_model, "observed_price": a.observed_price, "observed_price_date": str(a.observed_price_date),
        "outlook": s.get("outlook"), "ai_outlook": s.get("ai_outlook"), "risk_rating": s.get("risk_rating"),
        "base_target_12m": s.get("base_target_12m"), "bear_target_12m": s.get("bear_target_12m"),
        "bull_target_12m": s.get("bull_target_12m"), "base_return_12m": s.get("base_return_12m"),
        "forecast_model_version": a.forecast_model_version,
    }


DIFF_FIELDS = [
    ("price", "Price"), ("base_target_12m", "Base 12m target"), ("bear_target_12m", "Bear 12m target"),
    ("bull_target_12m", "Bull 12m target"), ("base_return_12m", "Base 12m return"), ("outlook", "Outlook"),
    ("risk_rating", "Risk rating"), ("revenue_growth_yoy", "Revenue growth YoY"), ("net_margin", "Net margin"),
    ("eps_ttm", "EPS (TTM)"), ("financial_data_version", "Financial data version"),
]


def diff_snapshots(cur: dict[str, Any], prev: dict[str, Any]) -> dict[str, Any]:
    changes = []
    for k, label in DIFF_FIELDS:
        a, b = prev.get(k), cur.get(k)
        if a != b:
            changes.append({"field": k, "label": label, "previous": a, "current": b})
    def setdiff(key: str) -> dict[str, list[str]]:
        p, c = set(prev.get(key) or []), set(cur.get(key) or [])
        return {"added": sorted(c - p), "removed": sorted(p - c)}
    return {"changes": changes, "bullish_points": setdiff("bullish_points"), "bearish_points": setdiff("bearish_points")}


def iso(dt: datetime | date | None) -> str | None:
    return dt.isoformat() if dt else None
